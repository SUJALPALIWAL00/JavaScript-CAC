// Data Types are of 2 types primite and non-primitive
// Primitive data types 
let name = "John";    // string
let age = 25;         // number
let isAdmin = true;    // boolean
let PI = 3.14;         // float
let isNull = null;     // Null
let isUndefined          // Undefined

console.log(name, age, isAdmin, PI, isNull, isUndefined);   

console.log(typeof name);    // Output: string
console.log(typeof age);     // Output: number
console.log(typeof isAdmin);    // Output: boolean
console.log(typeof PI);      // Output: number
console.log(typeof isNull);   // Output: object
console.log(typeof isUndefined);    // Output: undefined

/*
The datatype of null is an object but the data type of undefined is undefined.
*/

